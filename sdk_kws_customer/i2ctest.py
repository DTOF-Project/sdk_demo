def little_to_big_16bit(little_data):
    # 小端打包为字节（格式符'<H'），再按大端解包（格式符'>H'）
    big_data = struct.unpack('>H', struct.pack('<H', little_data))[0]
    return big_data

def little_block_to_big_16bit(block_data):
    
    big_block = []
    # 每2个字节为一组，转换为大端16位数据
    for i in range(0, len(block_data), 2):
        if i + 1 >= len(block_data):
            break  # 避免字节数为奇数时出错
        # 提取小端的2字节（低字节在前）
        little_bytes = block_data[i:i+2]
        # 小端打包→大端解包
        big_data = struct.unpack('>H', struct.pack('<H', little_bytes[1] << 8 | little_bytes[0]))[0]
        big_block.append(big_data)
    return big_block

def read_i2c_register(slave_addr, reg_addr, bus_number=1):
    
    try:
        # 创建I2C总线实例
        bus = smbus2.SMBus(bus_number)
        
        # 读取16位数据（小端模式，直接返回原始值）
        data = bus.read_word_data(slave_addr, reg_addr)
        
        # 关闭总线
        bus.close()
        
        return data
    
    except IOError as e:
        print(f"I2C通信错误: {e}")
        print("可能原因：设备未连接、地址错误、总线号错误或权限不足（需用sudo运行）")
        return None
    except Exception as e:
        print(f"其他错误: {e}")
        return None
    


def read_i2c_block(slave_addr, reg_addr, num_bytes, bus_number=1):
   
    try:
        # 创建I2C总线实例
        bus = smbus2.SMBus(bus_number)
        
        # 读取连续的num_bytes个字节
        data_array = bus.read_i2c_block_data(slave_addr, reg_addr, num_bytes)
        reversed_pairs = []
        for i in range(0, len(data_array), 2):
            if i + 1 < len(data_array):
                
                reversed_pairs.append(data_array[i+1])
                reversed_pairs.append(data_array[i])
            else:
                
                reversed_pairs.append(data_array[i])
        return reversed_pairs
    
    except IOError as e:
        print(f"I2C通信错误: {e}")
        print("可能原因：设备未连接、地址错误、总线号错误或权限不足（需用sudo运行）")
        return None
    except Exception as e:
        print(f"其他错误: {e}")
        return None

def write_i2c_register(slave_addr, reg_addr, data, bus_number=1):
    
    try:
        # 检查数据是否为16位有效范围（0-65535）
        if not (0 <= data <= 65535):
            print("错误：写入的数据必须是0-65535之间的16位整数")
            return False
        
        # 创建I2C总线实例
        bus = smbus2.SMBus(bus_number)
        
        # 写入16位数据（小端模式，直接使用原始数据）
        bus.write_word_data(slave_addr, reg_addr, data)
       
        
        # 关闭总线
        bus.close()
        
        return True  # 写入成功
    
    except IOError as e:
        print(f"I2C通信错误: {e}")
        return False
    except Exception as e:
        print(f"其他错误: {e}")
        return False
